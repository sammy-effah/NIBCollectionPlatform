CREATE TABLE IF NOT EXISTS role (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    create_date TIMESTAMP,
    email VARCHAR(255),
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    first_name VARCHAR(255),
    force_password_reset BOOLEAN NOT NULL DEFAULT FALSE,
    last_name VARCHAR(255),
    password VARCHAR(255) NOT NULL,
    phone_number VARCHAR(255),
    role_id BIGINT,
    username VARCHAR(255) NOT NULL UNIQUE,
    CONSTRAINT fk_users_role FOREIGN KEY (role_id) REFERENCES role (id)
);

CREATE TABLE IF NOT EXISTS institution (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TIMESTAMP,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    location VARCHAR(255),
    logo_location VARCHAR(255),
    name VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS donation_details (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    date TIMESTAMP,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    location VARCHAR(255),
    name VARCHAR(255) NOT NULL,
    pic_location VARCHAR(255),
    purpose VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS donation_collection (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount DOUBLE PRECISION,
    beneficiary TEXT,
    cheque VARCHAR(255),
    contributor_name TEXT,
    currency VARCHAR(255),
    date_data TIMESTAMP,
    description VARCHAR(255),
    donation_details_id BIGINT,
    items_and_quantity TEXT,
    phone VARCHAR(255),
    receipt_num VARCHAR(255),
    who_is_entering VARCHAR(255),
    CONSTRAINT fk_donation_collection_details
        FOREIGN KEY (donation_details_id) REFERENCES donation_details (id)
);

CREATE TABLE IF NOT EXISTS institution_pay_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount DOUBLE PRECISION,
    create_date TIMESTAMP,
    entered_by VARCHAR(255),
    index_number VARCHAR(255),
    institution_id BIGINT,
    level VARCHAR(255),
    name VARCHAR(255),
    phone_number VARCHAR(255),
    purpose VARCHAR(255),
    voucher_number VARCHAR(255),
    CONSTRAINT fk_pay_collections_institution
        FOREIGN KEY (institution_id) REFERENCES institution (id)
);
